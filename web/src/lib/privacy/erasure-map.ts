// `DELETE FROM app_users` is impossible in production: 141 foreign keys
// reference `app_users(id)` (fixture: `__fixtures__/app_users_fks.json`,
// regenerated by `scripts/db/app-users-fk-inventory.mjs --fixture`). Fourteen
// are `NO ACTION`, six `RESTRICT`, and two of the RESTRICT targets
// (`app_user_audit_log`, `reseller_audit_log`) are append-only ledgers whose
// rows can be neither updated nor deleted. Several financial ledgers
// (`credit_transactions`, `usage_logs`, `coupon_redemptions`,
// `referral_events`) carry a NOT NULL user reference and must be kept for
// the 7-year period the Privacy Policy states (clause 4, "Financial
// records"; s262A ITAA 1936, s286 Corporations Act 2001).
//
// So the erasure routine never deletes the `app_users` row. It walks this
// map inside one transaction (`erase_account()` RPC, migration 0348, re-created with the 125-entry map by 0351, the 126-entry map by 0356, the 127-entry maps by 0368/0370 — parallel branches — the merged 128-entry map by 0371, the 129-entry map by 0384–0386, the 132-entry map by 0393, the 133-entry map by 0405, the 134-entry map by 0406, the 138-entry map by 0417, the 139-entry map by 0421 and the 141-entry map by 0425) and
// finally turns the row into a pseudonymous TOMBSTONE — every PII column
// nulled, `email = 'deleted+<hash>@erased.blockid.au'`, `display_name =
// 'Deleted user'`, `erased_at` stamped — which the NOT NULL ledger references
// keep pointing at. The tombstone holds no personal information: the id is a
// random uuid and the hash is of that id, so nothing on the row identifies
// the person (APP 11.2 — "destroy or de-identify").
//
// Every FK in the fixture has exactly one entry here (pinned by
// `erasure-map.test.ts`, which also parses the VALUES list inside the
// migration so SQL and TypeScript cannot drift). Modes:
//
//   delete     the row is the user's own data → removed (cascades follow)
//   anonymise  the row is a ledger / legal record → kept; the user reference
//              is nulled when the column allows it and the row is telemetry
//              (`nullRef`), otherwise it stays on the tombstone; PII columns
//              are scrubbed (`scrub`); append-only ledgers are only counted
//              (`immutable`)
//   detach     the reference is to an actor on someone else's row
//              (referred_by, verified_by, reviewed_by, created_by, …) → NULL
//
// Retention exceptions (documented for the policy's "or on request" rows):
//   • Financial records (7 y): credit_transactions, usage_logs, revenue_events,
//     coupon_redemptions, referral_events, referrals, report_orders,
//     startup_package_purchases, checkout_session_reseller_commissions,
//     reseller_credit_grants, reseller_requests, reseller_attributions,
//     valuation_certificates (issued document), guest_analyses (Stripe ids).
//     Stripe itself keeps the customer + invoices; we cancel subscriptions
//     and detach payment methods but never delete the Stripe customer.
//   • Consent records (life of account + 7 y): consent_events, consents,
//     share_packages, equity_requests.
//   • Append-only security/audit ledgers: app_user_audit_log,
//     reseller_audit_log, audit_events (FK dropped in 0347 — the pseudonymous
//     actor id stays). upload_scans is a malware-scan log (30 d class).
//   • Cap-table / share-issuance records (life of entity + 7 y):
//     esop_option_grants (no FK — keyed by user_id without a constraint) are
//     left untouched on purpose.
//   • Evidence stored in Google Drive (evidence.storage_path is a Drive link)
//     is deleted at the row level only; the Drive object lives in the
//     user's own Drive, not ours.

export type ErasureMode = "delete" | "anonymise" | "detach";

export interface ErasureEntry {
  table: string;
  column: string;
  mode: ErasureMode;
  /**
   * Execution bucket, lower first. 10 = credentials, 15 = detaches,
   * 20 = children that must go before a parent with NO ACTION, 30 = user
   * data, 40 = parents whose cascades fan out, 50 = ledgers.
   */
  order: number;
  /** anonymise: also set the user column to NULL (column must be nullable). */
  nullRef?: boolean;
  /**
   * anonymise / detach: SQL `SET` fragment applied to matching rows.
   * `{anon_email}` is replaced with the tombstone address (quoted literal).
   */
  scrub?: string;
  /** anonymise: append-only ledger — counted, never written. */
  immutable?: boolean;
  note: string;
}

const D = (table: string, column: string, note: string, order = 30): ErasureEntry => ({ table, column, mode: "delete", order, note });
const X = (table: string, column: string, note: string, scrub?: string): ErasureEntry => ({ table, column, mode: "detach", order: 15, note, ...(scrub ? { scrub } : {}) });
const A = (
  table: string,
  column: string,
  note: string,
  extra: { nullRef?: boolean; scrub?: string; immutable?: boolean; order?: number } = {},
): ErasureEntry => ({ table, column, mode: "anonymise", order: extra.order ?? 50, note, ...extra });

