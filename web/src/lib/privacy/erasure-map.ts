export interface ErasureMapSummary {
  entries: number;
  tables: number;
  delete: number;
  anonymise: number;
  detach: number;
  immutable: number;
  project_detaches: number;
  non_fk_extras: number;
}

export function summariseErasureMap(map: readonly ErasureEntry[] = ERASURE_MAP): ErasureMapSummary {
  const s: ErasureMapSummary = {
    entries: map.length,
    tables: new Set(map.map((e) => e.table)).size,
    delete: 0,
    anonymise: 0,
    detach: 0,
    immutable: 0,
    project_detaches: PROJECT_DETACHES.length,
    non_fk_extras: NON_FK_EXTRAS.length,
  };
  for (const e of map) {
    s[e.mode]++;
    if (e.immutable) s.immutable++;
  }
  return s;
}

/** Entries in the order the RPC executes them (stable: order, table, column). */
export function orderedEntries(map: readonly ErasureEntry[] = ERASURE_MAP): ErasureEntry[] {
  return [...map].sort((a, b) => a.order - b.order || a.table.localeCompare(b.table) || a.column.localeCompare(b.column));
}
